export function getBotResponse(userQuestion: string): BotReply {
  const query = userQuestion.toLowerCase().trim();

  if (!query) {
    return {
      text: `สวัสดีครับ ผมคือ **Banana Assistant** ผู้ช่วยอัจฉริยะประจำ Banana Expert
ยินดีให้บริการข้อมูลใน 3 ส่วนหลัก:`,
      showQuickPillars: true,
    };
  }

  // Greetings
  if (/^(สวัสดี|หวัดดี|hi|hello|ดีครับ|ดีค่ะ|สอบถาม|ถามหน่อย|หวัดดีครับ|หวัดดีค่ะ)/i.test(query)) {
    return {
      text: `สวัสดีครับ ยินดีต้อนรับสู่ **Banana Expert** ครับ
สามารถเลือกหัวข้อที่สนใจด้านล่างเพื่อดูข้อมูลได้ทันทีครับ:`,
      showQuickPillars: true,
    };
  }

  // Thanks
  if (/^(ขอบคุณ|ขอบใจ|thank|thanks|ขอบคุณครับ|ขอบคุณค่ะ)/i.test(query)) {
    return {
      text: `ยินดีให้บริการเสมอครับ หากมีข้อสงสัยเรื่องการใช้งานเว็บไซต์ คลังความรู้กล้วย หรือข้อมูลฟาร์ม สามารถทักมาสอบถามได้ตลอดเวลาครับ`,
    };
  }

  // Find best topic match based on weighted score
  let bestTopic: KnowledgeTopic | null = null;
  let maxScore = 0;

  for (const topic of topics) {
    let score = 0;
    for (const kw of topic.keywords) {
      if (query.includes(kw.toLowerCase())) {
        score += kw.length * 2; // Keyword weight
      }
    }
    if (score > maxScore) {
      maxScore = score;
      bestTopic = topic;
    }
  }

  if (bestTopic && maxScore > 0) {
    return bestTopic.generateAnswer(query);
  }

  // Fallback organized by the 3 core pillars
  return {
    text: `สำหรับเรื่อง "${userQuestion}" นะครับ

คุณสามารถค้นหาข้อมูลที่เกี่ยวข้องได้จาก 3 เมนูหลักของเรา หรือเลือกหัวข้อด่วนด้านล่างได้เลยครับ:`,
    showQuickPillars: true,
    actionUrl: "/knowledge",
    actionLabel: "ไปที่คลังความรู้กล้วย",
  };
}
